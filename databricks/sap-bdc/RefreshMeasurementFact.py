# MAGIC ## Refresh the long-format measurement fact table
# MAGIC
# MAGIC Rebuilds `curated_measurement` (shared in the BDC data product as `curated.measurement`): one row per
# MAGIC measurement and series, `time, source, fragment, series, value, unit`. The import writes every measurement
# MAGIC fragment to its own `cdc_measurement_<fragment>` table with `<series>_value` / `<series>_unit` columns;
# MAGIC an Analytic Model in Datasphere needs one fact instead. The columns are discovered on every run, so new
# MAGIC fragments and series are picked up without changes. Runs as a task after the import in the import job.

# COMMAND ----------

dbutils.widgets.text("catalog", "factory", "Catalog")
dbutils.widgets.text("schema", "adhoc-demo_eu-latest-t2180777119", "Schema")
catalog = dbutils.widgets.get("catalog")
schema = dbutils.widgets.get("schema")
prefix = "cdc_measurement_"
target = f"`{catalog}`.`{schema}`.curated_measurement"

columns = {}
for r in spark.sql(f"""
        SELECT table_name, column_name FROM `{catalog}`.information_schema.columns
        WHERE table_schema = '{schema}' AND table_name LIKE '{prefix}%'""").collect():
    columns.setdefault(r["table_name"], set()).add(r["column_name"])


def literal(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


# One branch per series. Only creates: a measurement that was updated or deleted would otherwise
# appear twice, and (id, fragment, series) is the primary key.
branches = []
for table, cols in sorted(columns.items()):
    for column in sorted(c for c in cols if c.endswith("_value")):
        series = column[: -len("_value")]
        unit = f"`{series}_unit`" if f"{series}_unit" in cols else "CAST(NULL AS STRING)"
        branches.append(
            f"SELECT id, {literal(table[len(prefix):])} AS fragment, {literal(series)} AS series, time, source, "
            f"CAST(`{column}` AS DOUBLE) AS value, {unit} AS unit "
            f"FROM `{catalog}`.`{schema}`.`{table}` "
            f"WHERE eventType = 'MEASUREMENT_CREATE' AND `{column}` IS NOT NULL AND id IS NOT NULL")

# Created once with its key; INSERT OVERWRITE keeps the constraint (CREATE OR REPLACE would drop it)
spark.sql(f"""
    CREATE TABLE IF NOT EXISTS {target} (
        id STRING NOT NULL, fragment STRING NOT NULL, series STRING NOT NULL,
        time TIMESTAMP, source STRING, value DOUBLE, unit STRING,
        CONSTRAINT curated_measurement_pk PRIMARY KEY (id, fragment, series))
    COMMENT 'All measurement series in long format (generated by sap-bdc/RefreshMeasurementFact)'""")
spark.sql(f"INSERT OVERWRITE {target} " + "\nUNION ALL\n".join(branches))
print(spark.sql(f"SELECT COUNT(*) AS rows, COUNT(DISTINCT fragment, series) AS series, "
                f"COUNT(DISTINCT source) AS devices FROM {target}").first(), f"from {len(branches)} series columns")
