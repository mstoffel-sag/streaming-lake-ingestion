#!/usr/bin/env python3
"""Create the Grafana views grafana_series_values and grafana_device_series.

grafana_series_values: all measurement series in one long view (time, source,
metric, value, unit), so a dashboard can chart several series at once with
`WHERE metric IN (...)`. Each UNION ALL branch carries its metric as a
constant, so Databricks prunes every branch that isn't selected and only scans
the tables of the chosen series. The metric is the series name (health_score,
flow_ls, ...); a name can occur in several fragments, but never twice for one device.

grafana_device_series: a Delta table with one row per device and series (with the
device name from latest_inventory_inventory), for the dashboard's "pick a device,
then its series" lists. Computing it scans every measurement table (~30 s), so it
is materialized from the view grafana_device_series_v; the import job refreshes it
after every run (RefreshGrafanaLookup notebook). Materialized views would need
Pipelines, which this workspace doesn't have.

The import writes every Cumulocity measurement fragment to its own Delta table
(cdc_measurement_<fragment>) with flattened columns per series:
<series>_value and, if the series has a unit, <series>_unit. The view SQL is
generated from that layout, so re-run this script when new measurement types
or series appear (new devices and values are picked up automatically).

Runs through the SQL Statement Execution API with a Databricks CLI profile that
may create views in the schema. Usage (from databricks/grafana/):

    python3 series_views.py [--profile c8y-lake] [--warehouse f4848abbdab320fc]
                            [--catalog factory] [--schema adhoc-demo_eu-latest-t2180777119]
"""
import argparse
import json
import subprocess
import sys

PREFIX = "cdc_measurement_"
VALUES = "grafana_series_values"
LOOKUP = "grafana_device_series"
LOOKUP_VIEW = "grafana_device_series_v"
SEP = " · "  # device label = "<name> · <id>"; names are not unique


class Warehouse:
    def __init__(self, profile: str, warehouse: str):
        self.profile, self.warehouse = profile, warehouse

    def sql(self, statement: str) -> list:
        body = {"warehouse_id": self.warehouse, "statement": statement,
                "wait_timeout": "50s", "on_wait_timeout": "CANCEL"}
        res = subprocess.run(["databricks", "-p", self.profile, "api", "post", "/api/2.0/sql/statements",
                              "--json", json.dumps(body)], capture_output=True, text=True)
        if res.returncode:
            sys.exit(f"Databricks CLI: {res.stderr.strip()}")
        out = json.loads(res.stdout)
        if out["status"]["state"] != "SUCCEEDED":
            sys.exit(f"Databricks: {out['status'].get('error', {}).get('message', out['status'])}\n{statement}")
        return (out.get("result") or {}).get("data_array") or []


def ident(name: str) -> str:
    return "`" + name.replace("`", "``") + "`"


def literal(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def discover(wh: Warehouse, catalog: str, schema: str) -> list:
    """[(table, value column, unit column or None, metric label)] for every measurement series."""
    rows = wh.sql(f"""
        SELECT table_name, column_name
        FROM {ident(catalog)}.information_schema.columns
        WHERE table_schema = {literal(schema)} AND table_name LIKE '{PREFIX}%'
        ORDER BY table_name, ordinal_position""")
    columns = {}
    for table, column in rows:
        columns.setdefault(table, set()).add(column)
    series = []
    for table, cols in sorted(columns.items()):
        for column in sorted(c for c in cols if c.endswith("_value")):
            name = column[: -len("_value")]
            unit = f"{name}_unit" if f"{name}_unit" in cols else None
            series.append((table, column, unit, name))
    if not series:
        sys.exit(f"no measurement tables {PREFIX}* found in {catalog}.{schema}")
    return series


def values_sql(target: str, fq) -> str:
    branches = []
    for table, column, unit, metric in fq.series:
        unit_expr = ident(unit) if unit else "CAST(NULL AS STRING)"
        branches.append(
            f"SELECT time, source, {literal(metric)} AS metric,\n"
            f"       CAST({ident(column)} AS DOUBLE) AS value, {unit_expr} AS unit\n"
            f"FROM {fq.table(table)}\n"
            f"WHERE {ident(column)} IS NOT NULL")
    return (f"CREATE OR REPLACE VIEW {target}\n"
            f"COMMENT 'All measurement series, long format (generated by databricks/grafana/series_views.py)'\n"
            f"AS\n" + "\nUNION ALL\n".join(branches))


def lookup_sql(target: str, fq) -> str:
    return (
        f"CREATE OR REPLACE VIEW {target}\n"
        f"COMMENT 'Device/series lookup, materialized as {LOOKUP} (generated by databricks/grafana/series_views.py)'\n"
        f"AS SELECT s.source AS device_id,\n"
        f"       CASE WHEN i.name IS NULL THEN s.source ELSE CONCAT(i.name, '{SEP}', s.source) END AS device,\n"
        f"       s.metric, s.unit, s.measurements, s.first_time, s.last_time\n"
        f"FROM (\n"
        f"  SELECT source, metric, MAX(unit) AS unit, COUNT(*) AS measurements,\n"
        f"         MIN(time) AS first_time, MAX(time) AS last_time\n"
        f"  FROM {fq.table(VALUES)}\n"
        f"  GROUP BY source, metric\n"
        f") s\n"
        f"LEFT JOIN {fq.table('latest_inventory_inventory')} i ON i.id = s.source")


def refresh_sql(target: str, view: str) -> str:
    # Same statement as the RefreshGrafanaLookup notebook
    return f"CREATE OR REPLACE TABLE {target} AS SELECT * FROM {view}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--profile", default="c8y-lake")
    ap.add_argument("--warehouse", default="f4848abbdab320fc")
    ap.add_argument("--catalog", default="factory")
    ap.add_argument("--schema", default="adhoc-demo_eu-latest-t2180777119")
    args = ap.parse_args()

    wh = Warehouse(args.profile, args.warehouse)

    class fq:
        series = discover(wh, args.catalog, args.schema)

        @staticmethod
        def table(name):
            return f"{ident(args.catalog)}.{ident(args.schema)}.{ident(name)}"

    wh.sql(values_sql(fq.table(VALUES), fq))
    wh.sql(lookup_sql(fq.table(LOOKUP_VIEW), fq))
    wh.sql(refresh_sql(fq.table(LOOKUP), fq.table(LOOKUP_VIEW)))
    pairs, devices = wh.sql(f"SELECT COUNT(*), COUNT(DISTINCT device_id) FROM {fq.table(LOOKUP)}")[0]
    print(f"{VALUES}: {len({s[0] for s in fq.series})} tables, {len(fq.series)} series; "
          f"{LOOKUP}: {pairs} device/series pairs, {devices} devices")


if __name__ == "__main__":
    main()
