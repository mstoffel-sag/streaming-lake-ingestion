-- Read-only service user for Grafana (key-pair authentication).
-- Run as ACCOUNTADMIN in a worksheet after cumulocity_build_up.ipynb; replace T2180777119 with your tenant
-- and paste the public key (secrets/grafana_key.pub without the BEGIN/END lines) into RSA_PUBLIC_KEY.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS GRAFANA_CUMULOCITY_READER COMMENT = 'Grafana: read CURATED of the Cumulocity tenant databases';

GRANT USAGE ON WAREHOUSE CUMULOCITY_WH_T2180777119 TO ROLE GRAFANA_CUMULOCITY_READER;
GRANT USAGE ON DATABASE CUMULOCITY_T2180777119 TO ROLE GRAFANA_CUMULOCITY_READER;
GRANT USAGE ON SCHEMA CUMULOCITY_T2180777119.CURATED TO ROLE GRAFANA_CUMULOCITY_READER;
-- The build procedure replaces the tables and the view on schema changes; future grants cover the new objects.
-- SERIES_VALUES reads the raw Iceberg tables with the view owner's rights, so no grant on the raw database is needed.
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA CUMULOCITY_T2180777119.CURATED TO ROLE GRAFANA_CUMULOCITY_READER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA CUMULOCITY_T2180777119.CURATED TO ROLE GRAFANA_CUMULOCITY_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA CUMULOCITY_T2180777119.CURATED TO ROLE GRAFANA_CUMULOCITY_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA CUMULOCITY_T2180777119.CURATED TO ROLE GRAFANA_CUMULOCITY_READER;

-- TYPE = SERVICE: no password, no SSO, key pair only
CREATE USER IF NOT EXISTS GRAFANA_CUMULOCITY
  TYPE = SERVICE
  DEFAULT_ROLE = GRAFANA_CUMULOCITY_READER
  DEFAULT_WAREHOUSE = CUMULOCITY_WH_T2180777119
  COMMENT = 'Grafana data source (snowflake/grafana)';
ALTER USER GRAFANA_CUMULOCITY SET RSA_PUBLIC_KEY = '<public key>';
GRANT ROLE GRAFANA_CUMULOCITY_READER TO USER GRAFANA_CUMULOCITY;
